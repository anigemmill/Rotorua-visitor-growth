import type { GrowthBrief } from "@/generated/prisma";
import { Badge } from "@/components/ui";
import { ClaimBadge } from "@/components/ClaimBadge";
import type { BriefAction } from "@/lib/domain/brief";
import { formatDate } from "@/lib/format";

type Changed = { text: string; claimType: "FACT" | "OBSERVATION" | "INFERENCE" | "HYPOTHESIS" | "RECOMMENDATION"; source: string; illustrative?: boolean };

export function BriefView({ brief }: { brief: GrowthBrief }) {
  const changed = (brief.whatChanged as Changed[]) ?? [];
  const actions = (brief.actions as unknown as BriefAction[]) ?? [];
  return (
    <div className="space-y-4 text-sm">
      <div>
        <h4 className="text-xs font-semibold uppercase tracking-wide text-subtle">Scan — what changed</h4>
        {changed.length === 0 ? <p className="mt-1 text-muted">Nothing new recorded.</p> : (
          <ul className="mt-1.5 space-y-1.5">
            {changed.map((c, i) => (
              <li key={i} className="flex flex-wrap items-center gap-1.5">
                <ClaimBadge c={c.claimType} />
                <span>{c.text}</span>
                <span className="text-xs text-subtle">· {c.source}</span>
                {c.illustrative && <Badge tone="warning">Illustrative</Badge>}
              </li>
            ))}
          </ul>
        )}
      </div>
      <div>
        <h4 className="text-xs font-semibold uppercase tracking-wide text-subtle">Why it matters</h4>
        <p className="mt-1 whitespace-pre-wrap">{brief.whyItMatters ?? <span className="text-muted">—</span>}</p>
      </div>
      <div>
        <h4 className="text-xs font-semibold uppercase tracking-wide text-subtle">Brief — this week&apos;s actions (max 3)</h4>
        {actions.length === 0 ? <p className="mt-1 text-muted">No actions proposed.</p> : (
          <ol className="mt-1.5 list-decimal space-y-2 pl-5">
            {actions.map((a, i) => (
              <li key={i}>
                <p className="font-medium">{a.action}{a.needsApproval && <span className="ml-2"><Badge tone="warning">Needs approval</Badge></span>}</p>
                <p className="text-xs text-muted">Why: {a.why} · Owner: {a.owner} · Effort: {a.effort} · Measure: {a.measure}</p>
              </li>
            ))}
          </ol>
        )}
      </div>
      <div>
        <h4 className="text-xs font-semibold uppercase tracking-wide text-subtle">Learn — what worked</h4>
        <p className="mt-1 whitespace-pre-wrap">{brief.learnings ?? <span className="text-muted">Nothing to learn from formally yet.</span>}</p>
      </div>
      {brief.dataGaps.length > 0 && (
        <div>
          <h4 className="text-xs font-semibold uppercase tracking-wide text-subtle">Data gaps</h4>
          <ul className="mt-1 list-disc pl-5 text-muted">{brief.dataGaps.map((g) => <li key={g}>{g}</li>)}</ul>
        </div>
      )}
      <p className="text-xs text-subtle">
        Week of {formatDate(brief.weekOf)} · generated by {brief.generatedBy === "rules" ? "deterministic rules from stored data (no AI-written content)" : brief.generatedBy}
        {brief.approvedBy && ` · approved by ${brief.approvedBy} ${formatDate(brief.approvedAt)}`}
      </p>
    </div>
  );
}
